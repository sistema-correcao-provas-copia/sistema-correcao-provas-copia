-- Esquema PostgreSQL inicial para o Sistema de Correção de Provas.
-- Execute uma vez no banco remoto antes de configurar os secrets do app.

CREATE TABLE IF NOT EXISTS escola (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_inep VARCHAR(20),
    nome TEXT NOT NULL,
    cnpj VARCHAR(20),
    endereco TEXT,
    cidade TEXT,
    estado VARCHAR(2),
    telefone VARCHAR(30),
    email TEXT
);

CREATE TABLE IF NOT EXISTS responsavel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escola(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    cpf VARCHAR(20),
    email TEXT NOT NULL UNIQUE,
    telefone VARCHAR(30),
    senha_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS professor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escola(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    cpf VARCHAR(20),
    email TEXT NOT NULL UNIQUE,
    telefone VARCHAR(30),
    senha_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escola(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    UNIQUE (escola_id, nome)
);

CREATE TABLE IF NOT EXISTS materia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escola(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    UNIQUE (escola_id, nome)
);

CREATE TABLE IF NOT EXISTS aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escola(id) ON DELETE CASCADE,
    turma_id BIGINT NOT NULL REFERENCES turma(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    matricula TEXT,
    CONSTRAINT aluno_escola_matricula_unique UNIQUE (escola_id, matricula)
);

CREATE TABLE IF NOT EXISTS professor_turma_materia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES professor(id) ON DELETE CASCADE,
    turma_id BIGINT NOT NULL REFERENCES turma(id) ON DELETE CASCADE,
    materia_id BIGINT NOT NULL REFERENCES materia(id) ON DELETE CASCADE,
    UNIQUE (professor_id, turma_id, materia_id)
);

CREATE TABLE IF NOT EXISTS gabarito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escola(id) ON DELETE CASCADE,
    professor_id BIGINT NOT NULL REFERENCES professor(id) ON DELETE CASCADE,
    turma_id BIGINT NOT NULL REFERENCES turma(id) ON DELETE CASCADE,
    materia_id BIGINT NOT NULL REFERENCES materia(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    quantidade_questoes INTEGER NOT NULL CHECK (quantidade_questoes > 0),
    codigo_qr TEXT NOT NULL UNIQUE,
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS gabarito_questao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gabarito_id BIGINT NOT NULL REFERENCES gabarito(id) ON DELETE CASCADE,
    numero_questao INTEGER NOT NULL CHECK (numero_questao > 0),
    alternativa_correta VARCHAR(10) NOT NULL,
    peso NUMERIC(10, 4) NOT NULL DEFAULT 1,
    competencia TEXT,
    UNIQUE (gabarito_id, numero_questao)
);

CREATE TABLE IF NOT EXISTS folha_resposta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gabarito_id BIGINT NOT NULL REFERENCES gabarito(id) ON DELETE CASCADE,
    aluno_id BIGINT NOT NULL REFERENCES aluno(id) ON DELETE CASCADE,
    data_correcao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (gabarito_id, aluno_id)
);

CREATE TABLE IF NOT EXISTS resultado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folha_resposta_id BIGINT NOT NULL UNIQUE REFERENCES folha_resposta(id) ON DELETE CASCADE,
    quantidade_acertos INTEGER NOT NULL,
    quantidade_questoes INTEGER NOT NULL,
    nota NUMERIC(10, 4) NOT NULL,
    data_resultado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS resposta_aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folha_resposta_id BIGINT NOT NULL REFERENCES folha_resposta(id) ON DELETE CASCADE,
    numero_questao INTEGER NOT NULL,
    alternativa_marcada VARCHAR(10),
    UNIQUE (folha_resposta_id, numero_questao)
);

CREATE INDEX IF NOT EXISTS idx_aluno_turma ON aluno(turma_id);
CREATE INDEX IF NOT EXISTS idx_gabarito_professor_data ON gabarito(professor_id, data_criacao DESC);
CREATE INDEX IF NOT EXISTS idx_resultado_data ON resultado(data_resultado DESC);
